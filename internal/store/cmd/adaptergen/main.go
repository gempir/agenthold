// Command adaptergen generates the canonical store API and its PostgreSQL
// adapter from the two sqlc outputs. Run after sqlc generate (make gen-sql).
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/printer"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

type catalog struct {
	types   map[string]ast.Expr
	methods map[string]*ast.FuncDecl
}

func read(dir string) catalog {
	entries, err := os.ReadDir(dir)
	check(err)
	out := catalog{types: map[string]ast.Expr{}, methods: map[string]*ast.FuncDecl{}}
	for _, entry := range entries {
		if entry.IsDir() || !strings.HasSuffix(entry.Name(), ".go") || strings.HasSuffix(entry.Name(), "_test.go") {
			continue
		}
		file, err := parser.ParseFile(token.NewFileSet(), filepath.Join(dir, entry.Name()), nil, 0)
		check(err)
		for _, decl := range file.Decls {
			switch d := decl.(type) {
			case *ast.GenDecl:
				for _, spec := range d.Specs {
					if t, ok := spec.(*ast.TypeSpec); ok {
						out.types[t.Name.Name] = t.Type
					}
				}
			case *ast.FuncDecl:
				if d.Recv != nil && d.Name.Name != "WithTx" {
					out.methods[d.Name.Name] = d
				}
			}
		}
	}
	return out
}

func render(n ast.Node) string {
	var b bytes.Buffer
	check(printer.Fprint(&b, token.NewFileSet(), n))
	return b.String()
}

func check(err error) {
	if err != nil {
		panic(err)
	}
}

func write(path, source string) {
	out, err := format.Source([]byte(source))
	if err != nil {
		panic(fmt.Sprintf("%s: %v\n%s", path, err, source))
	}
	check(os.WriteFile(path, out, 0o644))
}

func sortedKeys[T any](m map[string]T) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

func qualified(t ast.Expr, prefix string, types map[string]ast.Expr) string {
	switch n := t.(type) {
	case *ast.Ident:
		if _, ok := types[n.Name]; ok {
			return prefix + "." + n.Name
		}
		return n.Name
	case *ast.ArrayType:
		if n.Len != nil {
			panic("fixed-size array not supported")
		}
		return "[]" + qualified(n.Elt, prefix, types)
	default:
		return render(t)
	}
}

// fromPG emits static conversions. Nested sqlc.embed rows need field-wise
// conversion because their embedded table structs are separate named types.
func fromPG(t ast.Expr, value string, types map[string]ast.Expr) string {
	id, ok := t.(*ast.Ident)
	if !ok {
		return value
	}
	expr, ok := types[id.Name]
	if !ok {
		return value
	}
	st, ok := expr.(*ast.StructType)
	if !ok {
		panic("unsupported result type " + id.Name)
	}
	nested := false
	for _, f := range st.Fields.List {
		if n, ok := f.Type.(*ast.Ident); ok {
			if _, ok = types[n.Name]; ok {
				nested = true
			}
		}
	}
	if !nested {
		return "db." + id.Name + "(" + value + ")"
	}
	fields := []string{}
	for _, f := range st.Fields.List {
		for _, name := range f.Names {
			fields = append(fields, name.Name+":"+fromPG(f.Type, value+"."+name.Name, types))
		}
	}
	return "db." + id.Name + "{" + strings.Join(fields, ",") + "}"
}

func main() {
	root := flag.String("root", ".", "repository root")
	flag.Parse()
	base := filepath.Join(*root, "internal/store")
	sq := read(filepath.Join(base, "sqlite"))
	pg := read(filepath.Join(base, "postgres"))
	header := "// Code generated by adaptergen from sqlc outputs. DO NOT EDIT.\n\n"
	aliases := header + "package db\n\nimport \"github.com/gempir/agenthold/internal/store/sqlite\"\n\n"
	for _, name := range sortedKeys(sq.types) {
		if name == "Queries" || name == "Querier" || name == "DBTX" {
			continue
		}
		aliases += "type " + name + " = sqlite." + name + "\n"
	}
	check(os.MkdirAll(filepath.Join(base, "db"), 0o755))
	// Old sqlc query implementation is deliberately removed from the facade.
	entries, err := os.ReadDir(filepath.Join(base, "db"))
	check(err)
	for _, entry := range entries {
		if strings.HasSuffix(entry.Name(), ".sql.go") || entry.Name() == "models.go" {
			check(os.Remove(filepath.Join(base, "db", entry.Name())))
		}
	}
	write(filepath.Join(base, "db/types.go"), aliases)
	write(filepath.Join(base, "db/querier.go"), header+"package db\n\nimport \"context\"\n\ntype Querier "+render(sq.types["Querier"])+"\n")
	src := header + "package store\n\nimport (\"context\";\"encoding/json\";\"github.com/gempir/agenthold/internal/store/db\";\"github.com/gempir/agenthold/internal/store/postgres\")\n\ntype postgresQueries struct{q *postgres.Queries}\nvar _ db.Querier=postgresQueries{}\n"
	for _, name := range sortedKeys(sq.methods) {
		m := sq.methods[name]
		other, ok := pg.methods[name]
		if !ok {
			panic("missing Postgres query " + name)
		}
		params := []string{}
		args := []string{}
		for i, f := range m.Type.Params.List {
			for _, n := range f.Names {
				params = append(params, n.Name+" "+qualified(f.Type, "db", sq.types))
				value := n.Name
				if i > 0 {
					if id, ok := f.Type.(*ast.Ident); ok {
						if _, ok = sq.types[id.Name]; ok {
							value = "postgres." + id.Name + "(" + value + ")"
						}
					}
				}
				args = append(args, value)
			}
		}
		resultTypes := []string{}
		for _, f := range m.Type.Results.List {
			resultTypes = append(resultTypes, qualified(f.Type, "db", sq.types))
		}
		result := strings.Join(resultTypes, ",")
		if len(resultTypes) > 1 {
			result = "(" + result + ")"
		}
		src += "\nfunc(p postgresQueries)" + name + "(" + strings.Join(params, ",") + ")" + result + "{\n"
		if name == "TransitionSandbox" {
			// PostgreSQL accepts one JSON value; SQLite expands the canonical list
			// as placeholders. Both support empty lists without special SQL assembly.
			src += "fromStates:=arg.FromStates;if fromStates==nil{fromStates=[]string{}};states,err:=json.Marshal(fromStates);if err!=nil{return 0,err}\n"
			src += "return p.q.TransitionSandbox(ctx,postgres.TransitionSandboxParams{ToState:arg.ToState,Error:arg.Error,Now:arg.Now,AgentID:arg.AgentID,FromStates:states})\n}\n"
			continue
		}
		if len(resultTypes) == 1 {
			src += "return p.q." + name + "(" + strings.Join(args, ",") + ")\n}\n"
			continue
		}
		// Refuse drift in method shapes; parameter/result field conversions are
		// checked by the Go compiler after generation.
		if len(other.Type.Results.List) != len(m.Type.Results.List) {
			panic("result mismatch: " + name)
		}
		src += "value,err:=p.q." + name + "(" + strings.Join(args, ",") + ")\n"
		out := m.Type.Results.List[0].Type
		if array, ok := out.(*ast.ArrayType); ok {
			src += "if err!=nil{return nil,err}\nresult:=make(" + qualified(out, "db", sq.types) + ",0,len(value))\nfor _,row:=range value{result=append(result," + fromPG(array.Elt, "row", sq.types) + ")}\nreturn result,nil\n}\n"
		} else {
			src += "return " + fromPG(out, "value", sq.types) + ",err\n}\n"
		}
	}
	write(filepath.Join(base, "postgres_adapter.gen.go"), src)
}

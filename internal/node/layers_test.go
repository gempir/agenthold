func makeTestLayer(t *testing.T, ref string, raw []byte) (LayerArtifact, []byte) {
	t.Helper()
	rawSum := sha256.Sum256(raw)
	var zbuf bytes.Buffer
	enc, err := zstd.NewWriter(&zbuf)
	if err != nil {
		t.Fatal(err)
	}
	if _, err := enc.Write(raw); err != nil {
		t.Fatal(err)
	}
	if err := enc.Close(); err != nil {
		t.Fatal(err)
	}
	zbytes := zbuf.Bytes()
	zSum := sha256.Sum256(zbytes)
	return LayerArtifact{
		Ref:        ref,
		SHA256:     hex.EncodeToString(rawSum[:]),
		Size:       int64(len(raw)),
		ZstdSHA256: hex.EncodeToString(zSum[:]),
		ZstdSize:   int64(len(zbytes)),
		Subdir:     "upper",
	}, zbytes
}

func TestLayerStoreSaveInstallResolve(t *testing.T) {
	ctrl := NewLayerStore(t.TempDir())
	edge := NewLayerStore(t.TempDir())

	raw := bytes.Repeat([]byte("ext4-layer-content-"), 2048)
	meta, zbytes := makeTestLayer(t, "image:img_1:1", raw)

	if err := ctrl.SaveZstd(meta, bytes.NewReader(zbytes)); err != nil {
		t.Fatalf("SaveZstd: %v", err)
	}
	f, err := ctrl.OpenZstd(meta.SHA256)
	if err != nil {
		t.Fatalf("OpenZstd: %v", err)
	}
	defer f.Close()

	has, err := edge.HasLayer(meta.Ref, meta.SHA256)
	if err != nil || has {
		t.Fatalf("HasLayer before install = (%v, %v), want (false, nil)", has, err)
	}
	if err := edge.InstallFromZstd(meta, f); err != nil {
		t.Fatalf("InstallFromZstd: %v", err)
	}
	has, err = edge.HasLayer(meta.Ref, meta.SHA256)
	if err != nil || !has {
		t.Fatalf("HasLayer after install = (%v, %v), want (true, nil)", has, err)
	}
	p, sub, err := edge.ResolveRef(meta.Ref)
	if err != nil {
		t.Fatalf("ResolveRef: %v", err)
	}
	if p != edge.RawPath(meta.SHA256) || sub != "upper" {
		t.Fatalf("ResolveRef = (%q, %q), want (%q, upper)", p, sub, edge.RawPath(meta.SHA256))
	}

	// Corrupt stream must be rejected.
	bad := meta
	bad.SHA256 = strings.Repeat("a", 64)
	if err := edge.InstallFromZstd(bad, bytes.NewReader(zbytes)); err == nil {
		t.Fatal("expected sha256 mismatch error")
	}
	if err := ValidateLayerRef("../escape"); err == nil {
		t.Fatal("expected path traversal ref to be rejected")
	}
}

func TestBuildScripts(t *testing.T) {
	runSh, setupSh, envDropIn := BuildScripts(
		[]string{"ripgrep", "python3-venv"},
		"echo hello-build",
		map[string]string{"Z_VAR": "2", "A_VAR": "1", "PATH": "/opt/custom/bin:$PATH"},
	)
	if !strings.Contains(runSh, "apt-get install -y -q --no-install-recommends 'ripgrep' 'python3-venv'") {
		t.Fatalf("missing apt install in runSh:\n%s", runSh)
	}
	if !strings.Contains(runSh, "bash /etc/agenthold/build-setup.sh") {
		t.Fatalf("missing setup script invocation:\n%s", runSh)
	}
	if !strings.Contains(setupSh, "echo hello-build") {
		t.Fatalf("setupSh missing script:\n%s", setupSh)
	}
	wantEnv := "# Custom image environment (generated by agenthold)\nA_VAR=1\nPATH=/opt/custom/bin:$PATH\nZ_VAR=2\n"
	if envDropIn != wantEnv {
		t.Fatalf("envDropIn = %q, want %q", envDropIn, wantEnv)
	}
}

func TestRemoteLayerTransport(t *testing.T) {
	r, b, _ := remoteFixture(t)
	ctx, cancel := context.WithTimeout(t.Context(), 10*time.Second)
	defer cancel()

	// Capacity includes Arch over remote yamux.
	capInfo, err := r.Capacity(ctx)
	if err != nil {
		t.Fatalf("Capacity: %v", err)
	}
	if capInfo.Arch != runtime.GOARCH {
		t.Fatalf("Capacity.Arch = %q, want %q", capInfo.Arch, runtime.GOARCH)
	}

	// PutLayer + HasLayer round-trip.
	raw := bytes.Repeat([]byte("remote-layer-"), 4096)
	meta, zbytes := makeTestLayer(t, "image:img_remote:3", raw)
	has, err := r.HasLayer(ctx, meta.Ref, meta.SHA256)
	if err != nil || has {
		t.Fatalf("HasLayer before = (%v, %v)", has, err)
	}
	if err := r.PutLayer(ctx, meta, bytes.NewReader(zbytes)); err != nil {
		t.Fatalf("PutLayer: %v", err)
	}
	has, err = r.HasLayer(ctx, meta.Ref, meta.SHA256)
	if err != nil || !has {
		t.Fatalf("HasLayer after = (%v, %v)", has, err)
	}

	// BuildLayer streaming logs + compressed artifact.
	builtRaw := []byte("built-layer-payload-from-remote-node")
	builtMeta, builtZstd := makeTestLayer(t, "image:img_build:1", builtRaw)
	b.SetLayerBuilder(func(_ context.Context, req LayerBuildRequest, onLog func(string)) (LayerBuildResult, io.ReadCloser, error) {
		onLog("line 1: " + req.BuildID)
		onLog("line 2: done")
		return LayerBuildResult{
			Arch:     runtime.GOARCH,
			BaseKey:  "base-test-key",
			Artifact: builtMeta,
		}, io.NopCloser(bytes.NewReader(builtZstd)), nil
	})
	var logs []string
	res, stream, err := r.BuildLayer(ctx, LayerBuildRequest{BuildID: "bld_123", ImageID: "img_build", Revision: 1}, func(line string) {
		logs = append(logs, line)
	})
	if err != nil {
		t.Fatalf("BuildLayer: %v", err)
	}
	gotZstd, err := io.ReadAll(stream)
	_ = stream.Close()
	if err != nil {
		t.Fatalf("read build artifact: %v", err)
	}
	if res.Arch != runtime.GOARCH || res.BaseKey != "base-test-key" || res.Artifact.SHA256 != builtMeta.SHA256 {
		t.Fatalf("BuildLayer result = %+v", res)
	}
	if !bytes.Equal(gotZstd, builtZstd) {
		t.Fatalf("streamed artifact mismatch: got %d bytes, want %d", len(gotZstd), len(builtZstd))
	}
	if len(logs) != 2 || logs[0] != "line 1: bld_123" || logs[1] != "line 2: done" {
		t.Fatalf("logs = %v", logs)
	}

	// BuildLayer failure propagates cleanly across yamux.
	b.SetLayerBuilder(func(_ context.Context, _ LayerBuildRequest, onLog func(string)) (LayerBuildResult, io.ReadCloser, error) {
		onLog("about to fail")
		return LayerBuildResult{}, nil, errors.New("apt-get failed with exit 100")
	})
	var failLogs []string
	_, _, err = r.BuildLayer(ctx, LayerBuildRequest{BuildID: "bld_fail"}, func(line string) {
		failLogs = append(failLogs, line)
	})
	if err == nil || !strings.Contains(err.Error(), "apt-get failed with exit 100") {
		t.Fatalf("expected build failure error, got: %v", err)
	}
	if len(failLogs) != 1 || failLogs[0] != "about to fail" {
		t.Fatalf("failLogs = %v", failLogs)
	}
}

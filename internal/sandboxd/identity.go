package sandboxd

import (
	"errors"
	"os"
	"path/filepath"
	"strings"
)

// InstanceFile records, on the system disk, which agent's sandbox it belongs
// to. A cloned disk still carries its source's id, which is how the clone
// finds out it is a copy. Systems that never booted with this file are
// stamped, not reset: only a disk that names another agent is a clone.
const InstanceFile = "/etc/agenthold/instance"

// instanceState lists, relative to the root, what identifies one machine and
// must not be shared by a clone. Docker's engine id and the machine id are
// what tools use to tell machines apart; ssh host keys and random seeds must
// never repeat.
var (
	// truncated keeps an empty file: the base image ships an empty machine-id.
	truncated = []string{"/etc/machine-id"}
	removed   = []string{
		"/var/lib/dbus/machine-id",
		"/var/lib/docker/engine-id",
		"/var/lib/systemd/random-seed",
		"/var/lib/urandom/random-seed",
	}
	// globs are removed too; sshd's keys are regenerated by the caller.
	globs = []string{"/etc/ssh/ssh_host_*"}
)

// EnsureIdentity makes the system under root belong to agentID. It reports
// true if the disk was copied from another agent's sandbox and its machine
// identity (see instanceState) was cleared. root is "/" in the guest.
func EnsureIdentity(root, agentID string) (reset bool, err error) {
	stamp := filepath.Join(root, InstanceFile)
	data, err := os.ReadFile(stamp)
	switch {
	case errors.Is(err, os.ErrNotExist):
		// First boot of this system: nothing to reset.
	case err != nil:
		return false, err
	case strings.TrimSpace(string(data)) == agentID:
		return false, nil
	default:
		reset = true
	}
	if reset {
		if err := clearIdentity(root); err != nil {
			return true, err
		}
	}
	// Written after the reset: a crash in between repeats the (idempotent) reset.
	if err := os.MkdirAll(filepath.Dir(stamp), 0o755); err != nil {
		return reset, err
	}
	return reset, writeFileAtomic(stamp, []byte(agentID+"\n"), 0o644)
}

func clearIdentity(root string) error {
	var errs []error
	for _, p := range truncated {
		if _, err := os.Lstat(filepath.Join(root, p)); err == nil {
			errs = append(errs, os.WriteFile(filepath.Join(root, p), nil, 0o644))
		}
	}
	for _, p := range removed {
		if err := os.Remove(filepath.Join(root, p)); err != nil && !errors.Is(err, os.ErrNotExist) {
			errs = append(errs, err)
		}
	}
	for _, g := range globs {
		matches, err := filepath.Glob(filepath.Join(root, g))
		if err != nil {
			errs = append(errs, err)
		}
		for _, m := range matches {
			if err := os.Remove(m); err != nil && !errors.Is(err, os.ErrNotExist) {
				errs = append(errs, err)
			}
		}
	}
	return errors.Join(errs...)
}

func writeFileAtomic(path string, data []byte, mode os.FileMode) error {
	tmp, err := os.CreateTemp(filepath.Dir(path), ".agenthold-*")
	if err != nil {
		return err
	}
	defer os.Remove(tmp.Name())
	if _, err := tmp.Write(data); err != nil {
		_ = tmp.Close()
		return err
	}
	if err := tmp.Chmod(mode); err != nil {
		_ = tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	return os.Rename(tmp.Name(), path)
}
